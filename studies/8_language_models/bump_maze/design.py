"""Design probe of the bump maze: the world, the exact solver, reference policies, chance rates and the optimum's
localisation curve. Writes design.md / design.json.

    PYTHONPATH=. .venv/bin/python studies/8_language_models/bump_maze/design.py
"""

from __future__ import annotations

import json, sys, time
from pathlib import Path

import numpy as np
import torch

from goalgeo import bumpmaze as BMZ

HERE = Path(__file__).resolve().parent
SEED, SIZE, LOOPS, N = 0, 9, 4, 4096


def rollout(w, sol, policy, N, seed):
    gen = torch.Generator().manual_seed(seed); e = BMZ.Env(w, N, gen); ret = torch.zeros(N); L = torch.full((N,), w.H)
    sizes, single, opt_sizes, qm_opt, by_step = [], [], [], [], []
    for t in range(w.H):
        a_opt, Q = BMZ.optimal_action(w, sol, e.filter.mask.numpy()); alive = ~e.done
        opt_set = Q >= Q.max(1, keepdims=True) - 1e-9
        if policy == "optimal": a = torch.as_tensor(a_opt)
        elif policy == "qmdp": a = BMZ.qmdp_action(w, e.filter.posterior)
        else: a = torch.randint(3, (N,), generator=gen)
        al = alive.numpy(); opt_sizes += list(opt_set[al].sum(1)); qm_opt += list(opt_set[al][np.arange(al.sum()), BMZ.qmdp_action(w, e.filter.posterior).numpy()[al]])
        was = e.done.clone(); r, _ = e.step(a); ret += r; L[~was & e.done] = t + 1
        alive = ~e.done; by_step.append((t + 1, float(alive.float().mean()), float(e.filter.mask[alive].sum(1).float().mean()) if alive.any() else 0.0))
        if alive.any(): single += list((e.filter.mask[alive].sum(1) == 1).numpy())
        if e.done.all(): break
    return dict(ret=float(ret.mean()), success=float((ret > 0).float().mean()), length=float(L.float().mean()), decisions=len(opt_sizes),
                chance_optimal=float(np.mean(np.array(opt_sizes) / 3)), opt_set_size=float(np.mean(opt_sizes)), qmdp_optimal=float(np.mean(qm_opt)),
                known_share=float(np.mean(single)), by_step=by_step)


def constant_policies(w, sol):
    """Constant-action and wall-following references: teacher-forced optimality on the zero-shot decisions and
    closed-loop success on the zero-shot starts."""
    sys.path.insert(0, str(HERE)); from zero_shot import optimum_decisions
    dec_all = optimum_decisions(w, sol, 512, 2000); rng = np.random.default_rng(3); pick = rng.choice(len(dec_all), 2048, replace=False); dec = [dec_all[i] for i in pick]
    starts = torch.as_tensor(w.start_states)[torch.randint(len(w.start_states), (2048,), generator=torch.Generator().manual_seed(1000))]
    out = {}
    for k, name in enumerate(("left", "right", "forward")):
        e = BMZ.Env(w, 2048, torch.Generator().manual_seed(0), start=starts); ret = torch.zeros(2048)
        for t in range(w.H): r, _ = e.step(torch.full((2048,), k)); ret += r
        out["always " + name] = dict(decision_optimal=float(np.mean([d["opt"][k] for d in dec])), ret=float(ret.mean()), success=float((ret > 0).float().mean()))
    e = BMZ.Env(w, 2048, torch.Generator().manual_seed(0), start=starts); ret = torch.zeros(2048); last_bump = torch.zeros(2048, dtype=torch.bool)
    for t in range(w.H):
        a = torch.where(last_bump, torch.full((2048,), 1), torch.full((2048,), 2)); r, o = e.step(a); ret += r; last_bump = (a == 2) & (o == 1)
    out["forward, right after a bump"] = dict(decision_optimal=None, ret=float(ret.mean()), success=float((ret > 0).float().mean()))
    return out


def main():
    w = BMZ.make(SEED, SIZE, LOOPS); t0 = time.time(); sol = BMZ.solve(w); t_solve = time.time() - t0
    res = dict(seed=SEED, size=SIZE, loops=LOOPS, free_cells=w.n_cells, states=w.n_states, start_states=len(w.start_states), goal=list(w.goal), belief_sets=len(sol["masks"]),
               V_uniform=float(sol["V"][0]), oracle=float(np.mean(w.gamma ** (w.dist[w.start_states] - 1))), oracle_length=float(np.mean(w.dist[w.start_states])), solve_seconds=t_solve, map=w.ascii())
    for pol in ("optimal", "qmdp", "random"):
        res[pol] = rollout(w, sol, pol, N, 0)
    res["constant"] = constant_policies(w, sol)
    (HERE / "design.json").write_text(json.dumps(res))
    o = res["optimal"]
    L = ["# Bump maze: design probe", "", f"Generated by `design.py`. Maze seed {SEED}, {SIZE} × {SIZE}, {LOOPS} loops: {w.n_cells} free cells, {w.n_states} states, {len(w.start_states)} start states, goal at (x {w.goal[0]}, y {w.goal[1]}); "
         f"{len(sol['masks'])} reachable belief sets, solved in {t_solve:.0f} s; V(uniform start) {sol['V'][0]:.3f}.", "", "```", w.ascii(), "```", "",
         f"| policy ({N} episodes) | return | success | mean length |", "|---|---|---|---|", f"| oracle (state known) | {res['oracle']:.3f} | 1 | {res['oracle_length']:.1f} |"]
    for pol, lab in (("optimal", "exact optimum"), ("qmdp", "QMDP"), ("random", "random")):
        r = res[pol]; L.append(f"| {lab} | {r['ret']:.3f} | {r['success']:.3f} | {r['length']:.1f} |")
    L += ["", f"Along the optimum's trajectories ({o['decisions']} decisions): optimal set size {o['opt_set_size']:.2f}, a random action is optimal in {o['chance_optimal']:.3f}, QMDP's action in {o['qmdp_optimal']:.3f}; "
          f"the state is known exactly in {o['known_share']:.3f} of decisions. Along random trajectories a random action is optimal in {res['random']['chance_optimal']:.3f}.", "",
          "Constant policies (teacher-forced optimality on the zero-shot decisions; closed-loop return and success on the zero-shot starts): " + "; ".join(f"{k}: " + (f"{v['decision_optimal']:.3f}, " if v['decision_optimal'] is not None else "") + f"{v['ret']:.3f}, {v['success']:.3f}" for k, v in res["constant"].items()) + ".", "",
          "Localisation under the optimum (move, share of episodes alive, mean size of the consistent set among them): " + ", ".join(f"({t}, {a:.2f}, {s:.1f})" for t, a, s in o["by_step"][:14]) + " …"]
    (HERE / "design.md").write_text("\n".join(L) + "\n"); print("\n".join(L))


if __name__ == "__main__":
    main()
