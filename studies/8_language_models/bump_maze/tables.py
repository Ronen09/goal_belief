"""tables.md from zero_shot.json, runs/*/results.json, probe.json and design.json (bump maze).

    .venv/bin/python studies/8_language_models/bump_maze/tables.py
"""

from __future__ import annotations

import argparse, json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent


def ci(x):
    return f"{x[0]:.2f}–{x[1]:.2f}"


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--out", default=str(HERE)); a = ap.parse_args()
    design = json.loads((HERE / "design.json").read_text())
    zs = json.loads((HERE / "zero_shot.json").read_text()) if (HERE / "zero_shot.json").exists() else {}
    runs = {p.parent.name: json.loads(p.read_text()) for p in sorted((HERE / "runs").glob("*/results.json"))} if (HERE / "runs").exists() else {}
    probe = {"n": None, "models": {}}
    for fn, suffix in (("probe_llm10000.json", "_10k"), ("probe.json", "_100k")):                 # the 10k file carries the base model and the from-scratch transformer too
        if (HERE / fn).exists():
            pj = json.loads((HERE / fn).read_text()); probe["n"] = pj["n"]
            for k, v in pj["models"].items(): probe["models"][k + suffix if k == "llm_finetuned" else k] = v
    if not probe["models"]: probe = {}
    o = design["optimal"]
    L = ["# Bump maze: tables", "", f"Generated by `tables.py`. The task: {design['free_cells']} free cells, {design['states']} states, {design['belief_sets']} reachable belief sets. "
         f"References ({design['optimal']['decisions']} decisions along the optimum): exact optimum return {o['ret']:.3f}, success {o['success']:.3f}, length {o['length']:.1f}; oracle {design['oracle']:.3f}; QMDP {design['qmdp']['ret']:.3f} (success {design['qmdp']['success']:.3f}); random {design['random']['ret']:.3f} (success {design['random']['success']:.3f}). "
         f"Teacher-forced decision optimality: chance {o['chance_optimal']:.3f}, QMDP {o['qmdp_optimal']:.3f}; the state is known in {o['known_share']:.3f} of the optimum's decisions.", ""]
    if zs:
        L += ["## Zero-shot", "", "| model | closed loop: return | success (95 % CI) | length | forward share | own decisions optimal | teacher-forced decision optimality (95 % CI) | known / unknown state | by set size 1 / 2–4 / 5–16 / > 16 |", "|---|---|---|---|---|---|---|---|---|"]
        for k, r in zs.items():
            d, c = r["decision"], r["closed_loop"]; bs = d["by_size"]
            L.append(f"| {k} | {c['ret']:.3f} | {c['success']:.2f} ({ci(c['success_ci'])}) | {c['length']:.1f} | {c['marginal'][2]:.2f} | {c['own_decisions_optimal']:.2f} | {d['optimal']:.3f} ({ci(d['ci'])}) | {d['known']:.2f} / {d['unknown']:.2f} | {bs['1']:.2f} / {bs['2-4']:.2f} / {bs['5-16']:.2f} / {bs['>16']:.2f} |")
        L += ["", "### Belief by questioning", "", "| model | cell AUC (decisions scored) | mismatched-history control | heading AUC | share answered yes |", "|---|---|---|---|---|"]
        for k, r in zs.items():
            if "belief" in r:
                b = r["belief"]; L.append(f"| {k} | {b['cell_auc'][0]:.3f} ({b['cell_auc'][1]}) | {b['mismatched_cell_auc'][0]:.3f} | {b['head_auc'][0]:.3f} | {b['yes_share']:.2f} |")
        for k, r in zs.items():
            if r.get("example_reply"): L += ["", f"Example reply ({k}):", "", "```", r["example_reply"], "```"]
        L.append("")
    if runs:
        L += ["## Trained on the task", "", "| model, training episodes | closed loop: return | success (95 % CI) | length | own decisions optimal | teacher-forced decision optimality (95 % CI) | by set size 1 / 2–4 / 5–16 / > 16 | minutes |", "|---|---|---|---|---|---|---|---|"]
        for k in sorted(runs, key=lambda k: (k.split("_")[0], int(k.split("_")[1]))):
            r = runs[k]; c, d = r["closed_loop"], r["teacher_forced"]; bs = d["by_size"]
            L.append(f"| {k.replace('_', ', ')} | {c['ret']:.3f} | {c['success']:.3f} ({ci(c['success_ci'])}) | {c['length']:.1f} | {c['own_decisions_optimal']:.2f} | {d['optimal']:.3f} ({ci(d['ci'])}) | {bs['1']:.2f} / {bs['2-4']:.2f} / {bs['5-16']:.2f} / {bs['>16']:.2f} | {r['seconds'] / 60:.0f} |")
        L.append(f"| exact optimum | {o['ret']:.3f} | {o['success']:.3f} | {o['length']:.1f} | 1 | 1 | | |")
        L.append("")
    if probe:
        L += ["## Belief probes", "", f"{probe['n']} decisions from the optimum's trajectories, held out by episode; a linear multi-label probe from the residual at the last transcript token to the consistent set's membership (per-decision AUC, exact recovery of the set, Jaccard) and a ridge probe to the log set size.", ""]
        for name, m in probe["models"].items():
            L += [f"### {name}", "", "| layer | membership AUC | exact set | Jaccard | log size R² |", "|---|---|---|---|---|"]
            for r in m["layers"]: L.append(f"| {r['layer']} | {r['auc']:.3f} | {r['exact']:.3f} | {r['jaccard']:.3f} | {r['size_r2']:.3f} |")
            L += [f"| MLP probe at layer {m['best_layer']} | {m['mlp_at_best']['auc']:.3f} | {m['mlp_at_best']['exact']:.3f} | {m['mlp_at_best']['jaccard']:.3f} | |", ""]
    # scorecard
    L += ["## Scorecard", "", "| | criterion | numbers | held |", "|---|---|---|---|"]
    if zs:
        sc = {k: r for k, r in zs.items() if not r["think"]}
        succ = {k: r["closed_loop"]["success_ci"][1] for k, r in sc.items()}; L.append(f"| Z-FLOOR | every zero-shot success ≤ 0.25 | upper CI: " + ", ".join(f"{k} {v:.2f}" for k, v in succ.items()) + f" | {'yes' if max(succ.values()) <= 0.25 else 'no'} |")
        dec = {k: r["decision"]["ci"][1] for k, r in sc.items()}; L.append(f"| Z-DEC | every zero-shot decision optimality ≤ 0.55 | upper CI: " + ", ".join(f"{k} {v:.2f}" for k, v in dec.items()) + f" | {'yes' if max(dec.values()) <= 0.55 else 'no'} |")
        k7, k05 = "Qwen2.5-7B-Instruct", "Qwen2.5-0.5B-Instruct"
        if k7 in sc and k05 in sc:
            diff = sc[k7]["decision"]["optimal"] - sc[k05]["decision"]["optimal"]; L.append(f"| Z-SCALE | 7B − 0.5B decision optimality ≥ 0.05 | {diff:.3f} | {'yes' if diff >= 0.05 else 'no'} |")
        au = {k: r["belief"]["cell_auc"][0] for k, r in sc.items() if "belief" in r}; L.append(f"| Z-BELIEF | every zero-shot cell AUC ≤ 0.65 | " + ", ".join(f"{k} {v:.2f}" for k, v in au.items()) + f" | {'yes' if max(au.values()) <= 0.65 else 'no'} |")
    if "llm_100000" in runs:
        r = runs["llm_100000"]; ok = r["closed_loop"]["success_ci"][0] >= 0.95 and r["closed_loop"]["ret"] >= 0.9 * o["ret"]
        L.append(f"| T-LEARN | fine-tuned 0.5B at 100 000: success ≥ 0.95 and return ≥ 0.9 × optimum | success {r['closed_loop']['success']:.3f} ({ci(r['closed_loop']['success_ci'])}), return {r['closed_loop']['ret']:.3f} / {o['ret']:.3f} = {r['closed_loop']['ret'] / o['ret']:.2f} | {'yes' if ok else 'no'} |")
        d = r["teacher_forced"]["by_size"]; L.append(f"| T-UNC | fine-tuned: optimality on sets > 16 ≥ 0.10 below size 1 | {d['1']:.3f} against {d['>16']:.3f} | {'yes' if d['1'] - d['>16'] >= 0.10 else 'no'} |")
    if "llm_10000" in runs and "tfm_10000" in runs:
        diff = runs["llm_10000"]["closed_loop"]["success"] - runs["tfm_10000"]["closed_loop"]["success"]
        L.append(f"| T-DATA | at 10 000 episodes, LLM success − from-scratch transformer's ≥ 0.10 | {runs['llm_10000']['closed_loop']['success']:.3f} − {runs['tfm_10000']['closed_loop']['success']:.3f} = {diff:.3f} | {'yes' if diff >= 0.10 else 'no'} |")
    if probe and ("llm_finetuned_100k" in probe["models"] or "llm_finetuned_10k" in probe["models"]) and "llm_base" in probe["models"]:
        ft = probe["models"].get("llm_finetuned_100k", probe["models"].get("llm_finetuned_10k")); base = probe["models"]["llm_base"]; b = ft["best_layer"]
        ft_auc = ft["layers"][b]["auc"]; base_auc = base["layers"][b]["auc"]
        L.append(f"| T-PROBE | fine-tuned best-layer membership AUC ≥ 0.95 and ≥ 0.15 above the base model's at that layer | layer {b}: {ft_auc:.3f} against base {base_auc:.3f} | {'yes' if ft_auc >= 0.95 and ft_auc - base_auc >= 0.15 else 'no'} |")
    Path(a.out, "tables.md").write_text("\n".join(L) + "\n"); print("\n".join(L))


if __name__ == "__main__":
    main()
