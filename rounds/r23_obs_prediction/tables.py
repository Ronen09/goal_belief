"""Round 23: tables from results.json.

    .venv/bin/python rounds/r23_obs_prediction/tables.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from scipy.stats import mannwhitneyu

OUT = Path("rounds/r23_obs_prediction")
ARMS = (("reward", "reward only"), ("aux1", "reward + prediction, c = 1"), ("aux01", "reward + prediction, c = 0.1"))
EDGES = (0.004, 0.006, 0.01, 0.02, 0.05)
f = lambda x, d=3: "—" if x is None or x != x else f"{x:.{d}f}"
row = lambda *c: "| " + " | ".join(str(x) for x in c) + " |"
head = lambda *c: [row(*c), "|" + "---|" * len(c)]
med = lambda v: f"{f(np.median(v))} ({f(min(v))}–{f(max(v))})"


def p_less(a, b):
    """One-sided exact rank-sum: is a below b?"""
    return float(mannwhitneyu(a, b, alternative="less", method="exact").pvalue)


def binned(R, arm, key, rng=None):
    """Mean of `key` within bins of regret, over checkpoints, for the seeds drawn (all if rng is None)."""
    seeds = list(R[arm])
    if rng is not None:
        seeds = [seeds[i] for i in rng.integers(len(seeds), size=len(seeds))]
    x = np.array([c["regret"] for s in seeds for c in R[arm][s]["curve"]]); y = np.array([c[key] for s in seeds for c in R[arm][s]["curve"]])
    b = np.digitize(x, EDGES)
    return np.array([y[b == i].mean() if (b == i).any() else np.nan for i in range(len(EDGES) + 1)]), np.bincount(b, minlength=len(EDGES) + 1)


def matched(R, arm, key, rng=None):
    ya, na = binned(R, arm, key, rng); yr, nr = binned(R, "reward", key, rng)
    ok = (na > 0) & (nr > 0)
    w = (na + nr) * ok
    return float(((ya - yr) * w)[ok].sum() / w.sum()) if w.sum() else np.nan


def main():
    r = json.load(open(OUT / "results.json")); R = r["runs"]
    last = lambda arm, key: [R[arm][s]["curve"][-1][key] for s in R[arm]]
    fin = lambda arm, cond, ty, cl, kind, key: [R[arm][s]["final"][cond][ty]["all_goals"][cl][kind][key] if kind else R[arm][s]["final"][cond][ty]["all_goals"][cl][key] for s in R[arm]]
    L = ["# Round 23 tables", "", "Generated by `rounds/r23_obs_prediction/tables.py`. Ten seeds per arm, final checkpoint unless stated; median (range). "
         "p: one-sided exact rank-sum test that the arm is below reward only.", "", "## 1. The three outcomes (natural access, no patch)", ""]
    outs = (("O1: type A, TV(hybrid, base)", "A_tv"), ("O1 secondary: probability crossing the optimal set", "A_crossing"), ("O1 secondary: greedy changed", "A_greedy_changed"),
            ("O2: type B same cells, greedy changed", "B_greedy_changed"), ("O2 secondary: TV", "B_tv"), ("O2 secondary: optimal to non-optimal", "B_greedy_lost"),
            ("O3: greedy regret", "regret"), ("O3: G1", "regret_G1"), ("O3: G2", "regret_G2"), ("O3: G3", "regret_G3"),
            ("probability on the optimal set, type A cells", "A_on_optimal"), ("probability on the optimal set, type B same cells", "B_on_optimal"), ("excess cross-entropy of the head (nats)", "excess_nll"))
    L += head("outcome", *[n for _, n in ARMS], "p (c = 1)", "p (c = 0.1)")
    for name, key in outs:
        d = 4 if key.startswith("regret") else 3
        L.append(row(name, *[f"{f(np.median(last(a, key)), d)} ({f(min(last(a, key)), d)}–{f(max(last(a, key)), d)})" for a, _ in ARMS],
                     *([f(p_less(last(a, key), last("reward", key))) for a in ("aux1", "aux01")] if "on_optimal" not in key and "excess" not in key else ["", ""])))
    L += ["", "Seeds with greedy regret above 0.05 on some goal: " + "; ".join(f"{n}: {sum(max(c[f'regret_G{g}'] for g in (1, 2, 3)) > 0.05 for c in [R[a][s]['curve'][-1] for s in R[a]])} of {len(R[a])}" for a, n in ARMS) + ".", "",
          "Excluding those seeds (post hoc):", ""] + head("outcome", *[n for _, n in ARMS], "p (c = 1)", "p (c = 0.1)")
    good = lambda a: [s for s in R[a] if max(R[a][s]["curve"][-1][f"regret_G{g}"] for g in (1, 2, 3)) <= 0.05]
    for name, key in outs[:7]:
        v = {a: [R[a][s]["curve"][-1][key] for s in good(a)] for a, _ in ARMS}
        L.append(row(name, *[med(v[a]) for a, _ in ARMS], f(p_less(v["aux1"], v["reward"])), f(p_less(v["aux01"], v["reward"]))))
    L += ["", "## 2. Per seed (final checkpoint)", ""] + head("arm", "seed", "regret", "G1", "G2", "G3", "O1", "O2", "excess nll")
    for a, n in ARMS:
        for s in R[a]:
            c = R[a][s]["curve"][-1]
            L.append(row(n, s[4:], f(c["regret"], 4), f(c["regret_G1"], 4), f(c["regret_G2"], 4), f(c["regret_G3"], 4), f(c["A_tv"]), f(c["B_greedy_changed"]), f(c["excess_nll"])))
    L += ["", "## 3. At equal regret: checkpoints from update 200, binned by greedy regret", "",
          "Mean over checkpoints in the bin (number of checkpoints).", ""]
    names = ["< 0.004", "0.004–0.006", "0.006–0.01", "0.01–0.02", "0.02–0.05", "> 0.05"]
    for name, key in (("O1: type A, TV(hybrid, base)", "A_tv"), ("O2: type B same cells, greedy changed", "B_greedy_changed")):
        L += ["", f"### {name}", ""] + head("arm", *names, "unmatched difference from reward only (final)", "difference within bins [95 %, bootstrap over seeds]")
        for a, n in ARMS:
            y, c = binned(R, a, key)
            ext = ["", ""]
            if a != "reward":
                rng = np.random.default_rng(0)
                bs = [matched(R, a, key, rng) for _ in range(2000)]
                ext = [f(np.median(last(a, key)) - np.median(last("reward", key))), f"{f(matched(R, a, key))} [{f(np.nanquantile(bs, 0.025))}, {f(np.nanquantile(bs, 0.975))}]"]
            L.append(row(n, *[f"{f(v)} ({k})" for v, k in zip(y, c)], *ext))
    L += ["", "## 4. Patches (kept separate): rank-13 PCA and whole patches of the prefix states", ""]
    rows = (("natural access — type C: moved, whole patch", "natural", "C", "disjoint", "whole", "moved"), ("natural access — type C: moved, pca patch", "natural", "C", "disjoint", "pca", "moved"),
            ("natural access — type C: share of the hybrid's gain, whole", "natural", "C", "disjoint", "whole", "d_optimal_share"),
            ("natural access — type B disjoint cells: moved, whole", "natural", "B", "disjoint", "whole", "moved"),
            ("condition 1, competence — type C: hybrid's greedy action in the donor's optimal set", "natural", "C", "disjoint", "hybrid", "greedy_optimal"),
            ("condition 2, conflicting routes — type B same cells: optimal to non-optimal under the whole patch", "natural", "B", "same", "whole", "greedy_lost"),
            ("same, under the natural swap (no patch)", "natural", "B", "same", "hybrid", "greedy_lost"),
            ("type A: TV from base under the whole patch", "natural", "A", "same", "whole", "tv_from_base"),
            ("direct route removed — type C: moved, pca patch", "direct_route_removed", "C", "disjoint", "pca", "moved"),
            ("direct route removed — type C: pca's share of the hybrid's gain", "direct_route_removed", "C", "disjoint", "pca", "d_optimal_share"),
            ("direct route removed — type C: the hybrid's gain on the donor's optimal set", "direct_route_removed", "C", "disjoint", "hybrid", "d_optimal"),
            ("condition 3, ablated competence — type C: hybrid's greedy action in the donor's optimal set", "direct_route_removed", "C", "disjoint", "hybrid", "greedy_optimal"),
            ("ablated competence — type A: probability on the optimal set, no patch", "direct_route_removed", "A", "same", None, "base_on_optimal"),
            ("direct route removed — type A: TV(hybrid, base)", "direct_route_removed", "A", "same", "hybrid", "tv_from_base"),
            ("direct route removed — type B same cells: greedy changed (hybrid)", "direct_route_removed", "B", "same", "hybrid", "greedy_changed"))
    L += head("measure", *[n for _, n in ARMS], "p: c = 1 above reward only", "p: c = 1 below")
    for name, *k in rows:
        v = {a: fin(a, *k) for a, _ in ARMS}
        L.append(row(name, *[f"{f(np.median(v[a]), 2)} ({f(min(v[a]), 2)}–{f(max(v[a]), 2)})" for a, _ in ARMS], f(p_less(v["reward"], v["aux1"])), f(p_less(v["aux1"], v["reward"]))))
    (OUT / "tables.md").write_text("\n".join(L) + "\n")
    print(len(L), "lines")


if __name__ == "__main__":
    main()
