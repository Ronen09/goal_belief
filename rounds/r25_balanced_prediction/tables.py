"""Round 25: tables from results.json.

    .venv/bin/python rounds/r25_balanced_prediction/tables.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from scipy.stats import mannwhitneyu, spearmanr

OUT = Path("rounds/r25_balanced_prediction")
ARMS = (("selected", "selected"), ("all", "balanced, all"), ("one", "balanced, one"), ("reward", "reward only"))
f = lambda x, d=3: "—" if x is None or x != x else f"{x:.{d}f}"
row = lambda *c: "| " + " | ".join(str(x) for x in c) + " |"
head = lambda *c: [row(*c), "|" + "---|" * len(c)]
p_less = lambda a, b: float(mannwhitneyu(a, b, alternative="less", method="exact").pvalue)


def main():
    R = json.load(open(OUT / "results.json"))["runs"]
    H = lambda *k: (lambda x: eval("x['head']" + "".join(f"[{q!r}]" for q in k)))
    rel = lambda k=None: (lambda x: (x["head"]["A"][k]["d_head"] / x["head"]["C"][k]["d_head"]) if k else x["head"]["relative_inconsistency"]["head"])
    pre = "lengths_2_3"
    M = (("P1: head's error against exact, goal token, all moves", H("A", "error"), 4, True), ("P2: identical-posterior inconsistency D_same, goal token, all moves", H("A", "d_head"), 4, True),
         ("P1, greedy move", H("A", "greedy_move", "error"), 4, True), ("P2, greedy move", H("A", "greedy_move", "d_head"), 4, True),
         ("P1, other three moves", H("A", "other_moves", "error"), 4, True), ("P2, other three moves", H("A", "other_moves", "d_head"), 4, True),
         ("P1, last prefix token (lengths 2–3)", H("A", "prefix_token", pre, "error"), 4, True), ("P2, last prefix token (lengths 2–3)", H("A", "prefix_token", pre, "d_head"), 4, True),
         ("P2 at the last prefix token of length 4 (no target in training)", H("A", "prefix_token", "length_4_untrained", "d_head"), 4, True),
         ("head: D_same / D_diff, all moves", rel(), 3, True), ("head: D_same / D_diff, greedy move", rel("greedy_move"), 3, True),
         ("head's error on type C histories, all moves", H("C", "error"), 4, True), ("excess cross-entropy, taken move (nats)", lambda x: x["excess_nll"], 4, True),
         ("Q1: policy inconsistency, type A TV", lambda x: x["policy"]["A"]["tv"], 4, False), ("Q1 secondary: relative to type C", lambda x: x["head"]["relative_inconsistency"]["policy"], 3, False),
         ("Q1 secondary: greedy changed, type A", lambda x: x["policy"]["A"]["greedy_changed"], 3, False), ("Q1 secondary: probability crossing the optimal set", lambda x: x["policy"]["A"]["crossing"], 3, False),
         ("O2: greedy changed where the optimal set is the same", lambda x: x["policy"]["B"]["greedy_changed"], 3, False),
         ("greedy regret", lambda x: x["regret"], 4, False), ("regret G1", lambda x: x["regret_G1"], 4, False), ("regret G2", lambda x: x["regret_G2"], 4, False), ("regret G3", lambda x: x["regret_G3"], 4, False),
         ("probability on the optimal set, type A cells", lambda x: x["policy"]["A"]["on_optimal"], 3, False))
    val = lambda arm, g: [g(R[arm][s]) for s in R[arm]]
    L = ["# Round 25 tables", "", "Generated by `rounds/r25_balanced_prediction/tables.py`. Ten seeds per arm, final checkpoint; median (range). p: one-sided exact rank-sum test "
         "that the arm is below the selected arm (p↑: above). The reward-only arm's head is untrained; its head measures are omitted.", ""]
    L += head("measure", *[n for _, n in ARMS], "p: all < selected", "p: one < selected", "p↑: all > selected", "p: all < one")
    for name, g, d, is_head in M:
        v = {a: val(a, g) for a, _ in ARMS}
        L.append(row(name, *[("—" if is_head and a == "reward" else f"{f(np.median(v[a]), d)} ({f(min(v[a]), d)}–{f(max(v[a]), d)})") for a, _ in ARMS],
                     f(p_less(v["all"], v["selected"])), f(p_less(v["one"], v["selected"])), f(p_less(v["selected"], v["all"])), f(p_less(v["all"], v["one"]))))
    L += ["", "Seeds with greedy regret above 0.05 on some goal: " + "; ".join(f"{n}: {sum(max(R[a][s][f'regret_G{g}'] for g in (1, 2, 3)) > 0.05 for s in R[a])} of {len(R[a])}" for a, n in ARMS) + ".", "",
          "## Across seeds: rank correlation between P2 (goal token, all moves) and Q1", ""] + head("arm", "Spearman ρ", "p", "with P2 on the greedy move: ρ", "p")
    for a, n in ARMS[:3]:
        x, y, z = val(a, H("A", "d_head")), val(a, lambda q: q["policy"]["A"]["tv"]), val(a, H("A", "greedy_move", "d_head"))
        s1, s2 = spearmanr(x, y), spearmanr(z, y)
        L.append(row(n, f(s1.statistic, 2), f(s1.pvalue), f(s2.statistic, 2), f(s2.pvalue)))
    x = [v for a in ("selected", "all", "one") for v in val(a, H("A", "d_head"))]; y = [v for a in ("selected", "all", "one") for v in val(a, lambda q: q["policy"]["A"]["tv"])]
    s = spearmanr(x, y); L.append(row("three arms pooled", f(s.statistic, 2), f(s.pvalue), "", ""))
    L += ["", "## Type A cells where the policy's greedy action differs between the two histories, and where it does not: D_same", ""] + head("arm", "share of cells", "differs", "same")
    for a, n in ARMS[:3]:
        L.append(row(n, *[f"{f(np.median(v))} ({f(min(v))}–{f(max(v))})" for v in (val(a, H("A", "greedy_differs")), val(a, H("A", "d_head_where_greedy_differs")), val(a, H("A", "d_head_where_greedy_same")))]))
    L += ["", "## Per seed", ""] + head("arm", "seed", "regret", "P1", "P2", "P1 greedy move", "P2 greedy move", "Q1", "O2", "excess nll")
    for a, n in ARMS:
        for s in R[a]:
            x = R[a][s]; h = x["head"]["A"]
            L.append(row(n, s[4:], f(x["regret"], 4), f(h["error"], 4), f(h["d_head"], 4), f(h["greedy_move"]["error"], 4), f(h["greedy_move"]["d_head"], 4), f(x["policy"]["A"]["tv"], 4), f(x["policy"]["B"]["greedy_changed"]), f(x["excess_nll"], 4)))
    (OUT / "tables.md").write_text("\n".join(L) + "\n")
    print(len(L), "lines")


if __name__ == "__main__":
    main()
